"""Revival planner: turn scan findings into reviewable starter files.

Design rules
------------
* Deterministic — the same repository always yields the same proposals.
* Safe — proposals are plain text; nothing is executed.  Applying a plan
  writes into a *copy* of the repository, never the original.
* Honest — only problems that can be fixed with a generic starter file get a
  proposal.  Anything that needs real tooling (e.g. a lockfile) is listed as
  a manual step instead.
* Never overwrites an existing file.
* Generated text avoids the words the scanner treats as code markers, so a
  revived repo does not gain new technical-debt findings.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass, field
from pathlib import Path

from app.scanner.models import Finding

PYTHON_MANIFESTS = {"pyproject.toml", "requirements.txt", "setup.py", "setup.cfg", "Pipfile"}
NODE_MANIFESTS = {"package.json"}

GENERATED_NOTE = "Generated by ReviveOps as a starting point. Review and adapt before relying on it."


@dataclass
class ProposedFile:
    """A file ReviveOps suggests adding to the repository."""

    path: str          # POSIX-style path relative to the repository root
    content: str
    finding_id: str    # the "missing" finding this proposal addresses
    rationale: str


@dataclass
class RevivalPlan:
    """All proposals for a repository plus steps that need a human."""

    project_type: str
    files: list[ProposedFile] = field(default_factory=list)
    manual_steps: list[str] = field(default_factory=list)


# ── Project type ──────────────────────────────────────────────────────


def detect_project_type(rel_paths: list[str]) -> str:
    """Return ``"python"``, ``"node"`` or ``"generic"`` from relative paths."""
    names = {Path(p).name for p in rel_paths}
    if names & NODE_MANIFESTS:
        return "node"
    if names & PYTHON_MANIFESTS or any(p.endswith(".py") for p in rel_paths):
        return "python"
    return "generic"


# ── Content generators ────────────────────────────────────────────────


def _readme(repo_name: str, project_type: str, rel_paths: list[str]) -> str:
    top = sorted({p.split("/")[0] + ("/" if "/" in p else "") for p in rel_paths})
    layout = "\n".join(f"- `{entry}`" for entry in top[:20]) or "- (empty)"
    names = {Path(p).name for p in rel_paths}

    if project_type == "python":
        if "requirements.txt" in names:
            setup = "pip install -r requirements.txt"
        elif "pyproject.toml" in names or "setup.py" in names:
            setup = "pip install -e ."
        else:
            setup = "# no dependency manifest found"
        steps = f"```bash\npython -m venv .venv\n. .venv/bin/activate\n{setup}\npython -m pytest\n```"
    elif project_type == "node":
        steps = "```bash\nnpm install\nnpm test\n```"
    else:
        steps = "Setup steps could not be detected automatically. Describe how to build and run the project here."

    return (
        f"# {repo_name}\n\n"
        f"> {GENERATED_NOTE}\n\n"
        "## Overview\n\n"
        f"Describe what {repo_name} does and who it is for.\n\n"
        "## Project layout\n\n"
        f"{layout}\n\n"
        "## Getting started\n\n"
        f"Detected project type: **{project_type}**.\n\n"
        f"{steps}\n\n"
        "## Contributing\n\n"
        "Open an issue or pull request. Run the tests before submitting changes.\n"
    )


_PY_SMOKE_TEST = '''"""Smoke test: every Python source file in the project must compile.

{note}
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {{".git", ".venv", "venv", "node_modules", "__pycache__", "build", "dist"}}


def _sources():
    return [
        p for p in ROOT.rglob("*.py")
        if not SKIP_DIRS.intersection(p.relative_to(ROOT).parts)
    ]


def test_python_sources_compile():
    for path in _sources():
        compile(path.read_text(encoding="utf-8"), str(path), "exec")
'''

_NODE_SMOKE_TEST = """// Smoke test: package.json must be valid JSON with a name.
// {note}
const test = require("node:test");
const assert = require("node:assert");
const fs = require("node:fs");
const path = require("node:path");

test("package.json is valid", () => {{
  const raw = fs.readFileSync(path.join(__dirname, "..", "package.json"), "utf8");
  const pkg = JSON.parse(raw);
  assert.ok(pkg.name, "package.json should declare a name");
}});
"""


def _smoke_test(project_type: str) -> tuple[str, str] | None:
    if project_type == "python":
        return "tests/test_smoke.py", _PY_SMOKE_TEST.format(note=GENERATED_NOTE)
    if project_type == "node":
        return "tests/smoke.test.js", _NODE_SMOKE_TEST.format(note=GENERATED_NOTE)
    return None


def _ci(project_type: str, rel_paths: list[str]) -> str | None:
    names = {Path(p).name for p in rel_paths}
    header = f"# {GENERATED_NOTE}\nname: CI\non: [push, pull_request]\n\njobs:\n  test:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n"
    if project_type == "python":
        if "requirements.txt" in names:
            install = "pip install -r requirements.txt pytest"
        elif "pyproject.toml" in names or "setup.py" in names:
            install = "pip install -e . pytest"
        else:
            install = "pip install pytest"
        return (
            header
            + "      - uses: actions/setup-python@v5\n        with:\n          python-version: \"3.12\"\n"
            + f"      - run: {install}\n      - run: python -m pytest\n"
        )
    if project_type == "node":
        return (
            header
            + "      - uses: actions/setup-node@v4\n        with:\n          node-version: 20\n"
            + "      - run: npm install\n      - run: npm test\n"
        )
    return None


def _dockerfile(project_type: str, rel_paths: list[str]) -> str | None:
    names = {Path(p).name for p in rel_paths}
    if project_type == "python":
        if "requirements.txt" in names:
            install = "RUN pip install --no-cache-dir -r requirements.txt\n"
        elif "pyproject.toml" in names or "setup.py" in names:
            install = "RUN pip install --no-cache-dir .\n"
        else:
            install = ""
        return (
            f"# {GENERATED_NOTE}\n"
            "FROM python:3.12-slim\nWORKDIR /app\nCOPY . .\n"
            f"{install}"
            "# Replace this command with your application's entry point.\n"
            'CMD ["python", "-m", "pytest"]\n'
        )
    if project_type == "node":
        return (
            f"# {GENERATED_NOTE}\n"
            "FROM node:20-slim\nWORKDIR /app\nCOPY . .\nRUN npm install\n"
            "# Replace this command with your application's entry point.\n"
            'CMD ["npm", "test"]\n'
        )
    return None


# ── Planner ───────────────────────────────────────────────────────────


def build_plan(
    repo_name: str,
    rel_paths: list[str],
    findings: list[Finding],
) -> RevivalPlan:
    """Build a revival plan from the repo's file list and scan findings."""
    rel_paths = sorted(p.replace("\\", "/") for p in rel_paths)
    project_type = detect_project_type(rel_paths)
    plan = RevivalPlan(project_type=project_type)
    missing = {f.finding_id for f in findings}
    existing = set(rel_paths)

    def propose(path: str, content: str | None, finding_id: str, why: str) -> None:
        if content is None or path in existing:
            return
        plan.files.append(ProposedFile(path, content, finding_id, why))

    if "doc-readme-missing" in missing:
        propose("README.md", _readme(repo_name, project_type, rel_paths),
                "doc-readme-missing", "Gives new contributors an overview and setup steps.")
    if "test-tests-missing" in missing:
        smoke = _smoke_test(project_type)
        if smoke:
            propose(smoke[0], smoke[1], "test-tests-missing",
                    "A minimal smoke test gives CI something to run and a place to add real tests.")
    if "ci-config-missing" in missing:
        propose(".github/workflows/ci.yml", _ci(project_type, rel_paths),
                "ci-config-missing", "Runs the tests automatically on every push.")
    if "docker-dockerfile-missing" in missing:
        propose("Dockerfile", _dockerfile(project_type, rel_paths),
                "docker-dockerfile-missing", "Makes the project buildable in a clean container.")

    if "dep-lockfile-missing" in missing:
        plan.manual_steps.append(
            "Generate a dependency lockfile with your package manager "
            "(for example `npm install` or `poetry lock`) — this needs the real "
            "dependency resolver, so ReviveOps does not fake it."
        )
    if "dep-manifest-missing" in missing:
        plan.manual_steps.append("Declare the project's dependencies in a manifest file.")
    if project_type == "generic" and plan.files == []:
        plan.manual_steps.append(
            "The project type could not be detected, so no starter files were generated."
        )
    return plan


# ── Applying a plan to a copy ─────────────────────────────────────────


def apply_plan_to_copy(
    source_files: list[tuple[Path, str]],
    plan: RevivalPlan,
    dest: Path,
) -> list[str]:
    """Copy *source_files* into *dest* and write the plan's files there.

    The original repository is never modified.  Returns the relative paths
    of the files that were added.
    """
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    dest_resolved = dest.resolve()

    for abs_path, rel in source_files:
        target = (dest / rel).resolve()
        if dest_resolved not in target.parents:
            continue  # defensive: never write outside the copy
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.copy2(abs_path, target)
        except OSError:
            continue

    written: list[str] = []
    for proposed in plan.files:
        target = (dest / proposed.path).resolve()
        if dest_resolved not in target.parents or target.exists():
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(proposed.content, encoding="utf-8")
        written.append(proposed.path)
    return written

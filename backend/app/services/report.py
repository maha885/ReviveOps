"""Markdown revival report renderer.

Generates a clean, structured Markdown document from a scan result,
score breakdown, and checklist.  The report can be downloaded as a .md file.
"""

from __future__ import annotations

from app.scanner.models import Finding, RecoveryTask, ScoreBreakdown

# Severity emoji/markers for the report.
SEVERITY_MARKERS: dict[str, str] = {
    "critical": "🔴",
    "high": "🟠",
    "medium": "🟡",
    "low": "🔵",
    "info": "⚪",
}


def render_report(
    repo_name: str,
    scanned_at: str,
    score: ScoreBreakdown,
    findings: list[Finding],
    tasks: list[RecoveryTask],
    file_count: int = 0,
    truncated: bool = False,
) -> str:
    """Render a Markdown revival report.

    Args:
        repo_name:    Repository name.
        scanned_at:   ISO timestamp.
        score:        Score breakdown with dimensions.
        findings:     All findings from the scan.
        tasks:        Recovery checklist tasks.
        file_count:   Number of files scanned.
        truncated:    Whether the scan was truncated.

    Returns:
        A Markdown string.
    """
    lines: list[str] = []

    # ── Header ─────────────────────────────────────────────────────────
    lines.append("# ReviveOps Revival Report")
    lines.append("")
    lines.append(f"**Repository:** `{repo_name}`  ")
    lines.append(f"**Scanned at:** {scanned_at}  ")
    lines.append(f"**Files scanned:** {file_count}  ")
    if truncated:
        lines.append("**Note:** Scan was truncated — file or time limits were reached.  ")
    lines.append("")

    # ── Score ──────────────────────────────────────────────────────────
    lines.append("## Revival Score")
    lines.append("")
    lines.append(f"**Overall: {score.total} / 100** _(heuristic — not a guarantee the project will run)_")
    lines.append("")
    lines.append("| Dimension | Score | Max | Explanation |")
    lines.append("|-----------|-------|-----|-------------|")
    for dim in score.dimensions:
        lines.append(f"| {dim.name} | {dim.score} | {dim.max_points} | {dim.explanation} |")
    lines.append("")

    # ── Findings ────────────────────────────────────────────────────────
    lines.append("## Findings")
    lines.append("")
    if not findings:
        lines.append("_No findings detected._")
        lines.append("")
    else:
        for f in findings:
            marker = SEVERITY_MARKERS.get(f.severity.value, "•")
            lines.append(f"### {marker} {f.title}")
            lines.append("")
            lines.append(f"- **Category:** {f.category.value}")
            lines.append(f"- **Severity:** {f.severity.value}")
            lines.append(f"- **Evidence:** {f.evidence}")
            lines.append(f"- **Recommendation:** {f.recommendation}")
            if f.source_path:
                lines.append(f"- **Source:** `{f.source_path}`")
            lines.append("")

    # ── Checklist ──────────────────────────────────────────────────────
    lines.append("## Recovery Checklist")
    lines.append("")
    if not tasks:
        lines.append("_No action items._")
        lines.append("")
    else:
        completed_count = sum(1 for t in tasks if t.completed)
        total_count = len(tasks)
        lines.append(f"**Progress:** {completed_count} / {total_count} completed")
        lines.append("")
        for t in tasks:
            check = "x" if t.completed else " "
            lines.append(f"- [{check}] **[{t.priority.upper()}]** {t.title}")
            lines.append(f"  - _Rationale:_ {t.rationale}")
            lines.append(f"  - _Evidence:_ {t.evidence}")
            lines.append(f"  - _Action:_ {t.recommended_action}")
            lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("_Generated by ReviveOps — local-first project revival workbench._")

    return "\n".join(lines)
